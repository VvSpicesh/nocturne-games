'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const game=fs.readFileSync(path.join(__dirname,'game.js'),'utf8');
const page=fs.readFileSync(path.join(__dirname,'index.html'),'utf8');
const css=fs.readFileSync(path.join(__dirname,'style.css'),'utf8');
const {TurnBeansEngine}=require('./engine.js');
for(const id of ['elapsed','bestTime','heartCount','homeHearts','failurePanel']) assert.match(page,new RegExp(`id="${id}"`));
for(const signature of ['function startTimer()', 'function pauseTimer()', 'function recordWin()', 'progress.bestTimes', 'progress.hearts', 'engine.isLost()', 'result.transfers','function makeFlights']) assert.ok(game.includes(signature),signature);
assert.match(game,/startTimer\(\)/);
assert.match(game,/recordWin\(\)/);
assert.match(game,/clearInterval\(timerInterval\)/);
assert.match(game,/progress\.elapsed\[level\.id\]/);
assert.match(css,/\.tray-heading,\.tray-label,\.tray-center small \{display:none!important\}/);
const board=[[{baseColor:'R',beanColor:'G'},{baseColor:'R',beanColor:'G'},{baseColor:'G',beanColor:'R'},{baseColor:'G',beanColor:'R'}]];
const e=new TurnBeansEngine(board);
e.take(0,0);
const out=e.click(0,2);
assert.equal(out.type,'exchange');
assert.equal(out.transfers.length,2);
assert.equal(out.transfers[0].sourceIndex,0);
assert.equal(out.transfers[1].sourceIndex,1);
assert.equal(e.undo().ok,true);
assert.equal(e.checkInvariants(),true);
console.log('PASS phase 15: timer, personal best, heart, failure, numeric trays, cross-tray animation metadata');
